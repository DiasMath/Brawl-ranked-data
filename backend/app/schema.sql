CREATE TABLE IF NOT EXISTS account_profile (
  player_tag VARCHAR(20) PRIMARY KEY,
  player_name VARCHAR(100) NOT NULL,
  raw TEXT NOT NULL,
  fetched_at TIMESTAMP(3) NOT NULL
);

CREATE TABLE IF NOT EXISTS battles (
  id VARCHAR(64) PRIMARY KEY,
  player_tag VARCHAR(20) NOT NULL,
  played_at TIMESTAMP(3) NOT NULL,
  event_id BIGINT,
  map_name VARCHAR(150),
  mode VARCHAR(100),
  api_type VARCHAR(50),
  ranked BOOLEAN NOT NULL,
  result VARCHAR(32),
  duration_seconds INT,
  player_brawler_id BIGINT,
  player_brawler VARCHAR(100),
  rank_label VARCHAR(60),
  rank_score INT,
  season VARCHAR(100),
  bans TEXT,
  raw TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS battle_players (
  battle_id VARCHAR(64) NOT NULL,
  team_index SMALLINT NOT NULL,
  slot SMALLINT NOT NULL,
  player_tag VARCHAR(20),
  player_name VARCHAR(100),
  brawler_id BIGINT,
  brawler VARCHAR(100),
  power INT,
  side VARCHAR(12) NOT NULL,
  PRIMARY KEY (battle_id, team_index, slot),
  CONSTRAINT player_battle FOREIGN KEY (battle_id) REFERENCES battles(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS update_log (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  player_tag VARCHAR(20) NOT NULL,
  started_at TIMESTAMP(3) NOT NULL,
  finished_at TIMESTAMP(3),
  status VARCHAR(20) NOT NULL,
  received INT,
  added INT,
  message VARCHAR(255)
);

ALTER TABLE update_log ADD COLUMN IF NOT EXISTS phase VARCHAR(24);
ALTER TABLE update_log ADD COLUMN IF NOT EXISTS processed INT;

CREATE TABLE IF NOT EXISTS battle_evidence (
  battle_id VARCHAR(64) PRIMARY KEY,
  rank_label VARCHAR(60),
  rank_score INT,
  season VARCHAR(100),
  bans TEXT,
  rank_reference VARCHAR(400),
  score_reference VARCHAR(400),
  season_reference VARCHAR(400),
  bans_reference VARCHAR(400),
  recorded_at TIMESTAMP(3) NOT NULL,
  CONSTRAINT evidence_battle FOREIGN KEY (battle_id) REFERENCES battles(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS meta_observations (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  player_tag VARCHAR(20) NOT NULL,
  source_name VARCHAR(120) NOT NULL,
  source_url VARCHAR(400) NOT NULL,
  period_start DATE NOT NULL,
  period_end DATE NOT NULL,
  map_name VARCHAR(150),
  mode VARCHAR(100),
  rank_label VARCHAR(60),
  season VARCHAR(100),
  brawler VARCHAR(100) NOT NULL,
  wins INT NOT NULL,
  games INT NOT NULL,
  pick_count INT,
  pick_total INT,
  ban_count INT,
  ban_total INT,
  recorded_at TIMESTAMP(3) NOT NULL
);
CREATE TABLE IF NOT EXISTS battle_collection (
  battle_id VARCHAR(64) PRIMARY KEY,
  first_seen_at TIMESTAMP(3) NOT NULL,
  delay_observed BOOLEAN NOT NULL,
  last_run_id BIGINT NOT NULL,
  CONSTRAINT collection_battle FOREIGN KEY (battle_id) REFERENCES battles(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS profile_readings (
  player_tag VARCHAR(20) NOT NULL,
  run_id BIGINT NOT NULL,
  observed_at TIMESTAMP(3) NOT NULL,
  trophies INT,
  rank_score INT,
  rank_label VARCHAR(60),
  season VARCHAR(100),
  PRIMARY KEY (player_tag, run_id)
);

CREATE TABLE IF NOT EXISTS collection_state (
  player_tag VARCHAR(20) PRIMARY KEY,
  last_possible_gap TIMESTAMP(3),
  retry_until TIMESTAMP(3)
);

CREATE INDEX IF NOT EXISTS battles_account_time ON battles (player_tag, played_at DESC);
CREATE INDEX IF NOT EXISTS battles_ranked_time ON battles (player_tag, ranked, played_at DESC);
CREATE INDEX IF NOT EXISTS updates_account_time ON update_log (player_tag, started_at DESC);
CREATE INDEX IF NOT EXISTS meta_account_period ON meta_observations (player_tag, period_start, period_end);
CREATE INDEX IF NOT EXISTS collection_run ON battle_collection (last_run_id);

CREATE TABLE IF NOT EXISTS meta_sample_battles (
  id VARCHAR(64) PRIMARY KEY,
  played_at TIMESTAMP(3) NOT NULL,
  map_name VARCHAR(150) NOT NULL,
  mode VARCHAR(50) NOT NULL,
  team_a INT[] NOT NULL,
  team_b INT[] NOT NULL,
  winner SMALLINT CHECK (winner IN (0, 1))
);

CREATE INDEX IF NOT EXISTS meta_sample_time ON meta_sample_battles (played_at);
ALTER TABLE meta_sample_battles ADD COLUMN IF NOT EXISTS observed_elo INT;

CREATE TABLE IF NOT EXISTS meta_sample_players (
  player_tag VARCHAR(20) PRIMARY KEY,
  next_check_at TIMESTAMP(3) NOT NULL,
  last_checked_at TIMESTAMP(3),
  ranked_elo INT
);
CREATE INDEX IF NOT EXISTS meta_sample_players_due ON meta_sample_players (next_check_at, player_tag);

CREATE TABLE IF NOT EXISTS meta_tracker_state (
  singleton BOOLEAN PRIMARY KEY DEFAULT TRUE CHECK (singleton),
  last_seed_at TIMESTAMP(3),
  last_run_at TIMESTAMP(3),
  retry_until TIMESTAMP(3)
);

CREATE TABLE IF NOT EXISTS tracked_accounts (
  player_tag VARCHAR(20) PRIMARY KEY,
  alias VARCHAR(60),
  created_at TIMESTAMP(3) NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC')
);

CREATE TABLE IF NOT EXISTS brawl_secrets.supercell_credentials (
  environment VARCHAR(12) PRIMARY KEY CHECK (environment IN ('development', 'production')),
  encrypted_token BYTEA NOT NULL,
  updated_at TIMESTAMP(3) NOT NULL
);

